import { useEffect, useState } from 'react';
import type { GenerationRecord, GenerationStatus } from '../core/character.ts';
import { GUIDE_KINDS } from '../core/character.ts';
import { store } from '../app/store.ts';
import { useApp } from '../app/useApp.ts';
import { NumberField, Section, download } from './controls.tsx';

const STATUS_LABEL: Record<GenerationStatus, string> = { candidate: 'Awaiting review', accepted: 'Accepted', rejected: 'Rejected' };

function Thumb({ assetId, alt }: { assetId: string | null; alt: string }) {
  const url = store.assetUrl(assetId);
  return <div className="thumb-lg checker">{url ? <img src={url} alt={alt} /> : null}</div>;
}

function ProviderBox() {
  const { ui, character: c } = useApp();
  const g = ui.generation;
  useEffect(() => {
    void store.checkProvider();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [g.localUrl]);
  const p = g.provider;
  return (
    <Section title="Generation backend" hint="Pose-guided generation needs a model running on this computer. CharacterForge does not include one and never uploads your artwork anywhere.">
      <label className="field col-field">
        <span>Server address</span>
        <input type="text" value={g.localUrl} data-testid="server-url" onChange={(e) => store.setLocalUrl(e.target.value)} spellCheck={false} />
      </label>
      <div className="row">
        <button onClick={() => void store.checkProvider()} disabled={g.checking} data-testid="check-server">
          {g.checking ? 'Checking…' : 'Check server'}
        </button>
      </div>
      <div className={`provider-status ${p?.state ?? 'unknown'}`} data-testid="provider-status" role="status">
        {!p ? (
          <span className="muted">Not checked yet.</span>
        ) : p.state === 'ready' ? (
          <>
            <b>Ready.</b> {p.message}
            {p.model && <div className="muted">Model: {p.model}</div>}
            {p.capabilities && (
              <div className="muted">
                Uses guides: {p.capabilities.guides.join(', ') || 'none'} · up to {p.capabilities.maxReferences} references
              </div>
            )}
          </>
        ) : (
          <>
            <b>{p.state === 'error' ? 'Problem:' : 'Generation is not available:'}</b> {p.message}
          </>
        )}
      </div>
      {c && (
        <label className="field col-field">
          <span>Instructions (optional)</span>
          <textarea rows={3} value={c.instructions} maxLength={4000} data-testid="instructions" placeholder="e.g. looking over her shoulder, wind in the hair, same outfit" onChange={(e) => store.setInstructions(e.target.value)} />
        </label>
      )}
      <div className="row">
        <NumberField label="Seed" value={g.seed ?? 0} digits={0} min={0} max={2147483647} width={96} onCommit={(n) => store.setSeed(Math.round(n))} />
        <button className="ghost" onClick={() => store.setSeed(null)} disabled={g.seed === null} title="Use a new random seed each time">
          {g.seed === null ? 'Random seed' : 'Back to random'}
        </button>
      </div>
      <div className="row">
        {g.running ? (
          <>
            <button className="danger" onClick={() => store.cancelGeneration()} data-testid="cancel-generation">
              Cancel
            </button>
            <span className="busy" data-testid="generation-stage">
              {g.stage || 'Working…'}
            </span>
          </>
        ) : (
          <button className="primary" disabled={!c?.originalAssetId || (p !== null && p.state !== 'ready')} data-testid="generate-button" onClick={() => void store.generate()} title={!c?.originalAssetId ? 'Import the original artwork first' : p && p.state !== 'ready' ? p.message : 'Generate a new illustration from the current pose'}>
            Generate from current pose
          </button>
        )}
      </div>
      {p && p.state !== 'ready' && (
        <p className="hint">
          Without a backend you can still use the studio: download the <b>guide pack</b> from the Pose studio, make the picture in your own tool (ComfyUI, Krita AI, drawing by hand…), then import it here to review, accept and keep it with this character.
        </p>
      )}
    </Section>
  );
}

function Provenance({ g }: { g: GenerationRecord }) {
  const p = g.provenance;
  const when = (t: number) => new Date(t).toLocaleString();
  const guides = GUIDE_KINDS.filter((k) => p.guideAssetIds[k.id]);
  return (
    <details className="provenance" open>
      <summary>Where this image came from</summary>
      <dl>
        <dt>Origin</dt>
        <dd>{g.origin === 'generated' ? `Generated by ${p.providerName}${p.model ? ` (model: ${p.model})` : ''}` : 'Imported by you — made outside CharacterForge; not claimed to be generated here'}</dd>
        <dt>Created</dt>
        <dd>{when(g.createdAt)}</dd>
        <dt>Pose</dt>
        <dd>{p.poseName ?? 'unsaved pose'} · camera {Math.round(p.camera.azimuth)}° / {Math.round(p.camera.elevation)}° · figure height {p.proportions.height.toFixed(2)}</dd>
        <dt>Inputs</dt>
        <dd>
          original artwork{p.referenceAssetIds.length ? ` + ${p.referenceAssetIds.length} reference${p.referenceAssetIds.length === 1 ? '' : 's'}` : ''}
          {guides.length ? ` + guides: ${guides.map((k) => k.label.toLowerCase()).join(', ')}` : ''}
        </dd>
        <dt>Settings</dt>
        <dd>
          {p.settings.width}×{p.settings.height}
          {p.settings.seed !== null ? ` · seed ${p.settings.seed}` : ''}
          {p.settings.instructions ? ` · “${p.settings.instructions}”` : ''}
        </dd>
        {p.parentId && (
          <>
            <dt>Retry of</dt>
            <dd>
              <button className="ghost small" onClick={() => store.selectResult(p.parentId)}>
                an earlier result
              </button>
            </dd>
          </>
        )}
      </dl>
      {guides.length > 0 && (
        <div className="row wrap">
          {guides.map((k) => (
            <figure key={k.id} className="guide-thumb checker">
              <img src={store.assetUrl(p.guideAssetIds[k.id]) ?? ''} alt={`${k.label} guide used`} />
              <figcaption>{k.label}</figcaption>
            </figure>
          ))}
        </div>
      )}
    </details>
  );
}

function Review({ g }: { g: GenerationRecord }) {
  const { character: c, ui } = useApp();
  if (!c) return null;
  const outInfo = store.assetInfo(g.outputAssetId);
  const origInfo = store.assetInfo(c.originalAssetId);
  const file = () => {
    const f = store.resultFile(g.id);
    if (f) download(f.bytes, f.fileName, f.mime);
  };
  return (
    <div className="review" data-testid="review">
      <div className="compare">
        <figure>
          <figcaption>
            <span className="chip original">ORIGINAL ARTWORK</span> <span className="muted">never modified</span>
          </figcaption>
          <Thumb assetId={c.originalAssetId} alt="Original artwork" />
          {origInfo && <p className="hint">{origInfo.width}×{origInfo.height}px</p>}
        </figure>
        <figure>
          <figcaption>
            <span className={`chip ${g.origin}`} data-testid="origin-chip">{g.origin === 'generated' ? 'GENERATED' : 'IMPORTED — NOT GENERATED HERE'}</span>{' '}
            <span className={`chip status-${g.status}`} data-testid="status-chip">{STATUS_LABEL[g.status]}</span>
          </figcaption>
          <Thumb assetId={g.outputAssetId} alt="Result" />
          {outInfo && <p className="hint">{outInfo.width}×{outInfo.height}px · {outInfo.mime.replace('image/', '').toUpperCase()}</p>}
        </figure>
      </div>
      <div className="row wrap">
        <button className="primary" disabled={g.status === 'accepted'} data-testid="accept" onClick={() => store.decideResult(g.id, 'accepted')}>
          Accept
        </button>
        <button disabled={g.status === 'rejected'} data-testid="reject" onClick={() => store.decideResult(g.id, 'rejected')}>
          Reject
        </button>
        {g.status !== 'candidate' && (
          <button className="ghost" onClick={() => store.decideResult(g.id, 'candidate')}>
            Back to review
          </button>
        )}
        <button disabled={g.origin !== 'generated' || ui.generation.running} title={g.origin === 'generated' ? 'Restore this result’s pose and generate again with a new seed' : 'Imported images cannot be regenerated'} data-testid="retry" onClick={() => void store.retryResult(g.id)}>
          Retry with same pose
        </button>
      </div>
      <div className="row wrap">
        <button onClick={() => store.sendResultToCanvas(g.id)} title="Adds a copy as a new layer in the 2D canvas for cropping, masking or touch-ups">
          Edit in 2D canvas
        </button>
        <button onClick={() => store.addResultAsReference(g.id)} title="Use this result as an additional reference (the original stays the original)">
          Use as reference
        </button>
        <button onClick={file}>Download</button>
        <button className="danger" disabled={g.status === 'accepted'} title={g.status === 'accepted' ? 'Un-accept first' : ''} onClick={() => window.confirm('Delete this result from the profile?') && store.removeResult(g.id)}>
          Delete
        </button>
      </div>
      <label className="field col-field">
        <span>Note</span>
        <input type="text" value={g.note} maxLength={4000} placeholder="What to fix, what you liked…" onChange={(e) => store.setResultNote(g.id, e.target.value)} />
      </label>
      <Provenance g={g} />
    </div>
  );
}

export function GenerateView() {
  const { character: c, ui } = useApp();
  const [filter, setFilter] = useState<'all' | GenerationStatus>('all');
  if (!c) return null;
  const list = [...c.generations].reverse().filter((g) => filter === 'all' || g.status === filter);
  const selected = c.generations.find((g) => g.id === ui.generation.selectedResultId) ?? null;
  return (
    <div className="workspace generate" data-testid="generate-view">
      <aside className="panel left gen-left">
        <div className="panel-h">
          <h2>Generate</h2>
        </div>
        <div className="scroll">
          <Section title="Inputs">
            <div className="inputs-row">
              <figure>
                <Thumb assetId={c.originalAssetId} alt="Original artwork" />
                <figcaption>Original</figcaption>
              </figure>
              <div>
                <p>
                  {c.references.filter((r) => r.approved).length} approved reference{c.references.filter((r) => r.approved).length === 1 ? '' : 's'}
                </p>
                <p className="muted">
                  Pose: {c.studio.poses.find((p) => JSON.stringify(p.pose) === JSON.stringify(c.studio.pose))?.name ?? 'current (unsaved)'} · {c.studio.output.width}×{c.studio.output.height}
                </p>
                <button onClick={() => store.setWorkspace('studio')}>Adjust pose…</button>
              </div>
            </div>
            {!c.originalAssetId && <p className="warn">Import the original artwork in the Character tab first.</p>}
          </Section>
          <ProviderBox />
        </div>
      </aside>
      <main className="center review-center">
        <div className="scroll pad">{selected ? <Review g={selected} /> : <p className="muted pad">{c.generations.length ? 'Select a result on the right to review it.' : 'No results yet. Generate one, or import an image you made elsewhere.'}</p>}</div>
      </main>
      <aside className="panel right">
        <div className="panel-h">
          <h2>Results</h2>
          <select aria-label="Filter results" value={filter} onChange={(e) => setFilter(e.target.value as typeof filter)}>
            <option value="all">All ({c.generations.length})</option>
            <option value="candidate">Awaiting review</option>
            <option value="accepted">Accepted</option>
            <option value="rejected">Rejected</option>
          </select>
        </div>
        <div className="scroll">
          <div className="row">
            <label className="button" title="Import an image you made elsewhere for review. It will be labelled as imported.">
              Import a result image…
              <input
                type="file"
                accept="image/png,image/jpeg,image/webp"
                hidden
                data-testid="import-result"
                onChange={(e) => {
                  const f = e.target.files?.[0];
                  e.target.value = '';
                  if (f) void store.importResult(f);
                }}
              />
            </label>
          </div>
          <ul className="results" data-testid="results">
            {list.map((g) => (
              <li key={g.id} className={`result${g.id === selected?.id ? ' sel' : ''}`} data-testid="result-item" onClick={() => store.selectResult(g.id)}>
                <Thumb assetId={g.outputAssetId} alt="Result thumbnail" />
                <div>
                  <span className={`chip status-${g.status}`}>{STATUS_LABEL[g.status]}</span>
                  <span className="muted">{g.origin === 'imported' ? 'imported' : 'generated'}</span>
                  <div className="muted">{new Date(g.createdAt).toLocaleString()}</div>
                </div>
              </li>
            ))}
          </ul>
          {list.length === 0 && <p className="muted pad">Nothing here.</p>}
        </div>
      </aside>
    </div>
  );
}
