import type { CharacterState } from './character.ts';
import type { Transform, Vec2 } from './math.ts';

export type { Transform, Vec2 };
export type ID = string;

export interface Layer {
  id: ID;
  name: string;
  kind: 'raster' | 'group';
  parentId: ID | null;
  visible: boolean;
  locked: boolean;
  /** 0..1 */
  opacity: number;
  /** Pixel asset (raster only). Never modified after creation. */
  assetId: ID | null;
  /** Optional alpha mask asset, same pixel size as the pixel asset. Alpha channel = visibility. */
  maskAssetId: ID | null;
  /** Pixel size of the asset (raster only). */
  width: number;
  height: number;
  /** Rest placement: canvas position of the pivot, rotation (deg), scale. */
  transform: Transform;
  /** Pivot in layer pixel coordinates. */
  pivot: Vec2;
  /** Joint this layer follows when posed (raster only). */
  jointId: ID | null;
}

export interface Joint {
  id: ID;
  name: string;
  parentId: ID | null;
  /** Rest position relative to the parent joint (absolute canvas position for roots). */
  offset: Vec2;
  /** Allowed rotation range in degrees relative to rest, or null for unlimited. */
  limits: { min: number; max: number } | null;
  /** Preferred IK bend side when this joint is the middle of a 2-bone chain. 0 = keep current side. */
  bend: -1 | 0 | 1;
}

export interface PoseState {
  /** Joint rotation in degrees relative to the parent frame. Missing = 0. */
  rotations: Record<ID, number>;
  /** Translation applied to every root joint. */
  rootOffset: Vec2;
}

export interface NamedPose extends PoseState {
  id: ID;
  name: string;
  createdAt: number;
}

export interface DocState {
  canvas: { width: number; height: number };
  layers: Layer[]; // array order = z-order among siblings, first = bottom
  joints: Joint[];
  pose: PoseState;
  poses: NamedPose[];
}

/** source = an imported original file; layer/mask = 2D editor pixels; reference = character reference image;
 *  guide = rendered pose guide; generated = a result image (generated by a provider or imported by the user). */
export type AssetKind = 'source' | 'layer' | 'mask' | 'reference' | 'guide' | 'generated';
export const ASSET_KINDS: readonly AssetKind[] = ['source', 'layer', 'mask', 'reference', 'guide', 'generated'];

export interface AssetInfo {
  id: ID;
  kind: AssetKind;
  mime: string;
  width: number;
  height: number;
  /** Byte length, used for bundle integrity checks. */
  size: number;
}

export interface SourceInfo {
  assetId: ID;
  fileName: string;
  mime: string;
  kind: 'png' | 'psd' | 'jpeg' | 'webp';
  importedAt: number;
}

export interface ProjectFile {
  schemaVersion: number;
  id: ID;
  name: string;
  createdAt: number;
  updatedAt: number;
  /** Every imported original file, preserved byte-for-byte as an asset. */
  sources: SourceInfo[];
  assets: AssetInfo[];
  /** 2D layer canvas (layout / rig / 2D pose). Retained as a secondary editing tool. */
  doc: DocState;
  /** Character profile: original artwork, references, 3D studio state and generated results (schema v2+). */
  character: CharacterState;
}

export const REST_POSE: PoseState = { rotations: {}, rootOffset: { x: 0, y: 0 } };

export function isRestPose(p: PoseState): boolean {
  return (
    Math.abs(p.rootOffset.x) < 1e-9 &&
    Math.abs(p.rootOffset.y) < 1e-9 &&
    Object.values(p.rotations).every((r) => Math.abs(r) < 1e-9)
  );
}
